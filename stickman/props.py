"""Prop library: 72 code-drawn objects in the same pen as the figures.

Each prop is a list of shapes in a unit box (x right, y down, roughly -0.5..0.5):
  ("L", points, closed)            a line / outline
  ("P", points, fill)              a filled polygon with outline
  ("R", x0, y0, x1, y1, fill)      a rounded box
  ("C", cx, cy, r, fill)           a circle
  ("A", cx, cy, r, a0, a1)         an arc (degrees, 0 = right, clockwise)
  ("T", x, y, text, size)          a few letters ("Zz", "$", "?")
fill is a palette key the look turns into a colour (a, b, c, d, e, light, dark, ink) or None.
Ink-only looks use pale tints; Colour Pop fills them brightly.
"""
import math


def _star(r1, r2, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        r = r1 if i % 2 == 0 else r2
        a = math.radians(rot + i * 180 / n)
        pts.append((math.cos(a) * r, math.sin(a) * r))
    return pts


def _heart(s=0.42):
    pts = []
    for k in range(40):
        t = 2 * math.pi * k / 40
        x = 16 * math.sin(t) ** 3
        y = -(13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t))
        pts.append((x / 17 * s, y / 17 * s + 0.03))
    return pts


def _cloud(cx=0.0, cy=0.0, s=1.0):
    return [("C", cx - 0.2 * s, cy + 0.04 * s, 0.16 * s, "light"), ("C", cx + 0.2 * s, cy + 0.05 * s, 0.15 * s, "light"),
            ("C", cx, cy - 0.06 * s, 0.22 * s, "light"), ("R", cx - 0.3 * s, cy + 0.02 * s, cx + 0.32 * s, cy + 0.2 * s, "light")]


